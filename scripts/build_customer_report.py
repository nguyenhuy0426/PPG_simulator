"""Data for the client report (docs/model-report/trinh-bay.html): writes docs/model-report/media/report-data.js.

Every number comes from the PPG-physiGPT run records in docs/physigpt/ (results.json and evidence/); the other
figures of the page are images of the paper (docs/paper/figures) and existing media, not data drawn here.

    python3 scripts/build_customer_report.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
PHYSIGPT = ROOT/"docs/physigpt"
EVIDENCE = PHYSIGPT/"evidence"
OUT = ROOT/"docs/model-report/media/report-data.js"

# 14 features of judge_physigpt.signal_features, in its order, with the labels shown on the page
FEATURES = {
    "rate_bpm": "Nhịp tim", "acf_peak": "Độ đều giữa các nhịp", "diff_std": "Độ dốc (sai phân bậc 1)",
    "diff2_std": "Chi tiết mịn (sai phân bậc 2)", "skew": "Độ lệch dáng sóng", "kurtosis": "Độ nhọn dáng sóng",
    "diff_skew": "Lên nhanh, xuống chậm", "mean_level": "Mức trung bình", "centroid_hz": "Trọng tâm phổ",
    "power_0.5-1.5 Hz": "Công suất 0,5–1,5 Hz", "power_1.5-3 Hz": "Công suất 1,5–3 Hz",
    "power_3-5 Hz": "Công suất 3–5 Hz", "power_5-8 Hz": "Công suất 5–8 Hz", "power_8-20 Hz": "Công suất 8–20 Hz",
}


def jsonl(path):
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def curve(path, after=0, until=None):
    rows = [r for r in jsonl(path) if "valid_flow" in r and r["step"] > after and (until is None or r["step"] <= until)]
    return [[r["step"], round(r["valid_flow"], 5)] for r in rows]


def wave(window, every=2):
    return [round(v, 3) for v in window[::every]]


def main():
    results = json.loads((PHYSIGPT/"results.json").read_text())
    variants = {v["variant"]: v for v in results["variants"]}
    large, base = variants["large, plateau stop + decay 3k"], variants["base, longer + sharpness loss 8"]
    stage = json.loads((EVIDENCE/"ppg-physigpt-stage0-large-v1/stage_summary.json").read_text())
    best = stage["best"]["step"]
    stable = curve(EVIDENCE/"ppg-physigpt-stage0-large-v1/metrics.jsonl", after=400)
    decay = [[best, round(stage["best"]["valid_flow"], 5)]]+curve(EVIDENCE/"ppg-physigpt-decay0-large-v1/metrics.jsonl")
    real = json.loads((EVIDENCE/"ppg-physigpt-feature-hist-v1/examples_real.json").read_text())["real"]
    gen = json.loads((EVIDENCE/"ppg-physigpt-judge-decay0-large-v1/sample_windows.json").read_text())["windows"]
    bench = results["benchmark"]
    data = dict(
        benchmark=dict(
            criteria=bench["criteria"], held_people=bench["held_people"], real=bench["real_other_people"],
            models=[dict(name=m["name"], earlier=m["earlier_name"], verdict=m["verdict"], mean=m["mean_22"],
                         ci=m["ci_95_mean_22"], trees=m["tree_accuracy"], below=len(m["features_below_floor"]),
                         lowest=m["lowest"], lowest_value=m["lowest_value"]) for m in bench["models"]],
            diff={k: dict(point=v["point"], ci=v["ci_95"]) for k, v in bench["paired_differences_22"].items()}),
        physigpt=dict(
            relative=large["fidelity"]["relative_similarity"], mean_similarity=large["fidelity"]["mean_similarity"],
            reference=large["fidelity"]["reference"]["mean_similarity"], base_similarity=base["fidelity"]["mean_similarity"],
            tree_accuracy=large["fidelity"]["tree_accuracy"], valid_flow=large["valid_flow"],
            base_valid_flow=base["valid_flow"], parameters=large["parameters"], best_step=best,
            hours=round(stage["hours"]+large["hours"], 2),
            curve=dict(stable=stable, decay=decay),
            features=[dict(key=k, label=label, base=round(base["fidelity"]["similarity"][k], 3),
                           large=round(large["fidelity"]["similarity"][k], 3),
                           real=round(large["fidelity"]["reference"]["similarity"][k], 3)) for k, label in FEATURES.items()],
            strict=[dict(variant=v["variant"], d=v["strict"]["mean_d_prime"]) for v in results["variants"] if v["strict"]],
            controls=results["controls"],
            waves=dict(fs=20, real=[wave(w) for w in real[:3]], generated=[wave(w) for w in gen[:3]]),
        ),
    )
    OUT.write_text("// Generated by scripts/build_customer_report.py from docs/physigpt; do not edit by hand.\n"
                   f"window.REPORT = {json.dumps(data, ensure_ascii=False, separators=(',', ':'))};\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size//1024} KB)")


if __name__ == "__main__":
    main()
