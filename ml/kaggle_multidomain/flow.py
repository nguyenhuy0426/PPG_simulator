"""PhysioFlow: constructed rhythm scaffold + conditional rectified-flow 1D U-Net (30 s, 40 Hz PPG).

Rhythm is constructed, as in PhysioMix, so the commanded rate and irregularity hold exactly and
extrapolate: systolic peak times come from log-normal IBIs and are given to the network as a
beat-phase scaffold (sin, cos, present flag). Everything else (pulse shape, beat-to-beat amplitude,
baseline, motion artefact, sensor texture) is generated by a U-Net trained with flow matching on real
windows, each aligned to its own detected peaks. There is no adversarial critic and no circular output
filter (round 5: a circular band-limit alone made real windows detectable).

Training windows whose peaks cannot be trusted (masked rate label, too few peaks, peak rate far from the
label: most wrist-exercise windows) are learned without a scaffold, and a random share of the others
too, so the same network also generates unscaffolded. The scaffold encodes peak timing only; it is not a
measured ECG and the rate labels are PPG engineering labels.
"""
import math

import numpy as np
from scipy.signal import find_peaks
import torch
from torch import nn
from torch.nn import functional as F

from ml.kaggle_lsm.train_lsm import FS, LENGTH
from ml.kaggle_multidomain.labels import IRR_MAX
from ml.kaggle_multidomain.physio import view_mask

# Peak search as in labels.beat_stats; repairs below use the window's median interval m.
PEAK_DISTANCE_S, PEAK_PROMINENCE = .3, .3
MERGE_BELOW, FILL_ABOVE = .45, 1.7      # peaks closer than .45 m merge; gaps above 1.7 m get virtual peaks
MIN_PEAKS = 5
RATE_TOLERANCE = (6., .10)               # peak rate vs label: max(6 bpm, 10%)
HZ_RANGE = (.6, 3.3)                     # same carrier range as PhysioMix on the v3 view
BEATS = 160                              # constructed peaks per window (>= 30 s at 198 bpm)
FINISH_PAD = 6*FS                        # reflected samples each side for the optional finishing data-view filter
# The criterion's log-PSD (train_lsm.features): Welch, 10 s Hann segments, 50% overlap, normalised, log10(+1e-8).
WELCH, WELCH_HOP, LOG_PSD_FLOOR = 400, 200, 1e-8
SPECTRAL_T = .25                         # the log-PSD loss ramps from 1 at t=0 to 0 here (last 4 of 16 Heun steps)


def window_peaks(row, fs=FS):
    """Systolic peak times (samples, sub-sample) of one window after merge/fill repair; None if < 3 peaks."""
    span = np.percentile(row, 95)-np.percentile(row, 5)
    peaks, _ = find_peaks(row, distance=round(PEAK_DISTANCE_S*fs), prominence=PEAK_PROMINENCE*max(span, 1e-9))
    peaks = peaks[(peaks > 0) & (peaks < len(row)-1)]
    if len(peaks) < 3:
        return None
    a, b, c = row[peaks-1], row[peaks], row[peaks+1]
    den = a-2*b+c
    times = peaks+.5*(a-c)/np.where(den == 0, 1, den)
    m = np.median(np.diff(times))
    kept = [0]
    for i in range(1, len(times)):
        if times[i]-times[kept[-1]] < MERGE_BELOW*m:
            if row[peaks[i]] > row[peaks[kept[-1]]]:
                kept[-1] = i
        else:
            kept.append(i)
    times = times[kept]
    filled = [times[0]]
    for t in times[1:]:
        gap = t-filled[-1]
        if gap > FILL_ABOVE*m:
            k = int(round(gap/m))
            filled.extend(filled[-1]+gap*np.arange(1, k)/k)
        filled.append(t)
    return np.asarray(filled)


def phase_from_peaks(times, length=LENGTH):
    """Beat phase in cycles, linear between peaks, extended by the median interval beyond the ends."""
    m = float(np.median(np.diff(times)))
    before = times[0]-m*np.arange(int(np.ceil(times[0]/m))+1, 0, -1)
    after = times[-1]+m*np.arange(1, int(np.ceil((length-times[-1])/m))+2)
    knots = np.r_[before, times, after]
    return np.interp(np.arange(length), knots, np.arange(len(knots))-len(before)).astype(np.float32)


def real_scaffolds(signal, rate, rate_known):
    """(phase cycles (n, L) float32, usable (n,) bool) for real windows, judged against their rate labels."""
    phase = np.zeros(signal.shape, np.float32)
    usable = np.zeros(len(signal), bool)
    for i, row in enumerate(signal):
        if not rate_known[i]:
            continue
        times = window_peaks(row)
        if times is None or len(times) < MIN_PEAKS:
            continue
        bpm = 60*FS/np.median(np.diff(times))
        if abs(bpm-rate[i]) > max(RATE_TOLERANCE[0], RATE_TOLERANCE[1]*rate[i]):
            continue
        phase[i], usable[i] = phase_from_peaks(times, signal.shape[1]), True
    return phase, usable


def constructed_phase(z, hz, sigma, time, beats=BEATS):
    """Beat phase (cycles) whose integer crossings are peaks with log-normal IBIs (mean 1/hz, sigma).

    The peak noise is read from the far end of z (reversed), the first peak lies in (-IBI_0, 0]."""
    u = z.flip(1)
    ibi = torch.exp(sigma[:, None]*u[:, :beats]-.5*sigma[:, None]**2)/hz[:, None]
    first = -ibi[:, :1]*torch.sigmoid(u[:, beats:beats+1])
    peaks = first+torch.cumsum(ibi, 1)-ibi
    index = ((peaks[:, :, None] <= time[None, None]).sum(1)-1).clamp(0, beats-1)
    return index.to(z.dtype)+(time[None]-peaks.gather(1, index))/ibi.gather(1, index)


def scaffold(phase, present):
    """(n, 3, L): sin, cos of the beat phase and the present flag; absent rows are all zero."""
    flag = present.to(phase.dtype)[:, None]
    angle = 2*math.pi*phase
    return torch.stack((angle.sin()*flag, angle.cos()*flag, flag.expand_as(phase)), 1)


class ResBlock(nn.Module):
    def __init__(self, cin, cout, emb, kernel):
        super().__init__()
        self.norm1, self.norm2 = nn.GroupNorm(8, cin), nn.GroupNorm(8, cout)
        self.conv1 = nn.Conv1d(cin, cout, kernel, padding=kernel//2)
        self.conv2 = nn.Conv1d(cout, cout, kernel, padding=kernel//2)
        self.film = nn.Linear(emb, 2*cout)
        self.skip = nn.Conv1d(cin, cout, 1) if cin != cout else nn.Identity()
        nn.init.zeros_(self.conv2.weight)
        nn.init.zeros_(self.conv2.bias)

    def forward(self, x, emb):
        h = self.conv1(F.silu(self.norm1(x)))
        scale, shift = self.film(emb)[:, :, None].chunk(2, 1)
        h = self.conv2(F.silu(self.norm2(h)*(1+scale)+shift))
        return self.skip(x)+h


class Attention(nn.Module):
    def __init__(self, channels, heads=4):
        super().__init__()
        self.heads, self.dim = heads, channels//heads
        self.norm = nn.GroupNorm(8, channels)
        self.qkv = nn.Conv1d(channels, 3*channels, 1)
        self.proj = nn.Conv1d(channels, channels, 1)
        nn.init.zeros_(self.proj.weight)
        nn.init.zeros_(self.proj.bias)

    def forward(self, x):
        length = x.shape[-1]
        q, k, v = self.qkv(self.norm(x)).reshape(-1, 3*self.heads, self.dim, length).chunk(3, 1)
        weights = torch.softmax(torch.einsum("bhdi,bhdj->bhij", q, k)/math.sqrt(self.dim), -1)
        h = torch.einsum("bhij,bhdj->bhdi", weights, v).reshape(-1, self.heads*self.dim, length)
        return x+self.proj(h)


class UNet1D(nn.Module):
    """Velocity network v(x_t, t | scaffold, condition) on (n, 1, LENGTH) windows.

    Five resolutions (1200..75 samples), FiLM from time + condition embeddings, self-attention at 150 and
    75 samples (3.75 s and 7.5 s per token span covers several beats). cond_flag 0 is the unconditioned
    branch used for classifier-free guidance."""
    def __init__(self, cond_size, channels=(32, 64, 128, 160, 160), kernels=(5, 5, 3, 3, 3),
                 attention=(False, False, False, True, True), blocks=2, emb=256):
        super().__init__()
        self.register_buffer("freqs", torch.exp(-math.log(1e4)*torch.arange(64, dtype=torch.float32)/64))
        self.time_mlp = nn.Sequential(nn.Linear(128, emb), nn.SiLU(), nn.Linear(emb, emb))
        self.cond_mlp = nn.Sequential(nn.Linear(cond_size+1, emb), nn.SiLU(), nn.Linear(emb, emb))
        self.inp = nn.Conv1d(4, channels[0], 7, padding=3)
        self.down, self.down_attn, self.downsample = nn.ModuleList(), nn.ModuleList(), nn.ModuleList()
        skips, previous = [channels[0]], channels[0]
        for level, (width, kernel, attend) in enumerate(zip(channels, kernels, attention)):
            for _ in range(blocks):
                self.down.append(ResBlock(previous, width, emb, kernel))
                self.down_attn.append(Attention(width) if attend else nn.Identity())
                previous = width
                skips.append(width)
            if level < len(channels)-1:
                self.downsample.append(nn.Conv1d(width, width, 3, stride=2, padding=1))
                skips.append(width)
        self.mid1 = ResBlock(previous, previous, emb, kernels[-1])
        self.mid_attn = Attention(previous)
        self.mid2 = ResBlock(previous, previous, emb, kernels[-1])
        self.up, self.up_attn, self.upsample = nn.ModuleList(), nn.ModuleList(), nn.ModuleList()
        for level in reversed(range(len(channels))):
            width, kernel, attend = channels[level], kernels[level], attention[level]
            for _ in range(blocks+1):
                self.up.append(ResBlock(previous+skips.pop(), width, emb, kernel))
                self.up_attn.append(Attention(width) if attend else nn.Identity())
                previous = width
            if level > 0:
                self.upsample.append(nn.Conv1d(width, width, 3, padding=1))
        self.levels, self.blocks = len(channels), blocks
        self.out_norm = nn.GroupNorm(8, previous)
        self.out = nn.Conv1d(previous, 1, 3, padding=1)
        nn.init.zeros_(self.out.weight)
        nn.init.zeros_(self.out.bias)

    def forward(self, x, t, scaffold3, condition, cond_flag):
        angle = t[:, None]*1000*self.freqs[None]
        emb = self.time_mlp(torch.cat((angle.sin(), angle.cos()), 1))
        emb = emb+self.cond_mlp(torch.cat((condition*cond_flag[:, None], cond_flag[:, None]), 1))
        h = self.inp(torch.cat((x, scaffold3), 1))
        hs = [h]
        block = 0
        for level in range(self.levels):
            for _ in range(self.blocks):
                h = self.down_attn[block](self.down[block](h, emb))
                hs.append(h)
                block += 1
            if level < self.levels-1:
                h = self.downsample[level](h)
                hs.append(h)
        h = self.mid2(self.mid_attn(self.mid1(h, emb)), emb)
        block = 0
        for i, level in enumerate(reversed(range(self.levels))):
            for _ in range(self.blocks+1):
                h = self.up_attn[block](self.up[block](torch.cat((h, hs.pop()), 1), emb))
                block += 1
            if level > 0:
                h = self.upsample[i](F.interpolate(h, scale_factor=2., mode="nearest"))
        return self.out(F.silu(self.out_norm(h)))


def standardize(x):
    """Per-window zero mean, unit SD: the flow's data scale (noise is unit Gaussian)."""
    return (x-x.mean(-1, keepdim=True))/x.std(-1, keepdim=True).clamp_min(1e-6)


def flow_times(n, device, t_dist="logit"):
    """logit: logit-normal(0, 1), which rarely visits t < 0.05 where the last sampling steps and the fine
    texture live; uniform: U(0, 1); mix: half of each."""
    logit = torch.sigmoid(torch.randn(n, device=device))
    if t_dist == "logit":
        return logit
    uniform = torch.rand(n, device=device)
    if t_dist == "uniform":
        return uniform
    return torch.where(torch.rand(n, device=device) < .5, logit, uniform)


def log_psd(x):
    """(n, 200) log10 normalised Welch PSD of (n, 1, L) windows at 0.1-20 Hz, as train_lsm.features computes it
    (Hann, constant detrend per segment, one-sided density), in float32 so it can be a training loss."""
    segments = x[:, 0].float().unfold(-1, WELCH, WELCH_HOP)
    segments = segments-segments.mean(-1, keepdim=True)
    window = torch.hann_window(WELCH, periodic=True, dtype=segments.dtype, device=segments.device)
    # |X|^2 as re^2 + im^2: abs() of a zero (the detrended DC bin) has no clean gradient.
    power = torch.view_as_real(torch.fft.rfft(segments*window, dim=-1)).square().sum(-1).mean(1)
    power = torch.cat((power[:, :1], 2*power[:, 1:-1], power[:, -1:]), -1)
    power = power/power.sum(-1, keepdim=True).clamp_min(1e-12)
    return torch.log10(power[:, 1:]+LOG_PSD_FLOOR)


def stop_band_weight(view="v3"):
    """(200,) weight of each log_psd bin: 1 - |H|^2 of the data view on the Welch grid, ~0 in the pass band."""
    return torch.tensor(1-view_mask(view, WELCH)[1:])


def flow_loss(net, real, phase, present, condition, cond_drop=.1, scaffold_drop=.15, deriv=0., t_dist="logit",
              spectral=0., spectral_stop=False, input_noise=0.):
    """Rectified-flow velocity MSE; deriv adds an x0 first-difference term weighted towards low noise (the
    derivative C2ST probe reads exactly these differences).

    spectral adds a per-window log-PSD error of the x0 estimate against its own real window, ramped down to zero
    at SPECTRAL_T: near t=0 the estimate is what the last sampling steps output, and on the log scale the
    0.1-0.5 Hz and 12-20 Hz stop bands of the data view (where real windows sit at the floor) weigh as much as
    the pulse band. Mean over the batch, like the other terms. spectral_stop keeps only the stop bands
    (stop_band_weight): there every real window is at the floor, so the posterior-mean x0 estimate is ~0 at any t
    and the term only sharpens what the velocity MSE already asks for, without pulling the pulse band.

    input_noise (gamma) perturbs the network input with extra noise gamma*t*xi while the targets stay those of the
    unperturbed path (input perturbation against exposure bias, Ning et al. 2023): sampling trajectories leave the
    training marginal (wrist: the 12-20 Hz residual grows from the high-noise steps on), and with the x0 terms the
    network learns to return a clean estimate from a slightly noisier input than its time label says."""
    x0 = standardize(real)
    n = len(x0)
    t = flow_times(n, x0.device, t_dist)
    noise = torch.randn_like(x0)
    xt = (1-t[:, None, None])*x0+t[:, None, None]*noise
    if input_noise:
        xt = xt+input_noise*t[:, None, None]*torch.randn_like(x0)
    keep = (torch.rand(n, device=x0.device) >= cond_drop).to(x0.dtype)
    present = present & (torch.rand(n, device=x0.device) >= scaffold_drop)
    v = net(xt, t, scaffold(phase, present), condition, keep)
    loss = F.mse_loss(v, noise-x0)
    estimate = xt-t[:, None, None]*v
    if deriv:
        weight = (1-t)[:, None, None]**2
        loss = loss+deriv*(weight*(10*(torch.diff(estimate, dim=-1)-torch.diff(x0, dim=-1))).square()).mean()
    if spectral:
        weight = (1-t/SPECTRAL_T).clamp_min(0)
        error = (log_psd(estimate)-log_psd(x0)).square()
        if spectral_stop:
            bins = stop_band_weight().to(error.device)
            error = (error*bins).sum(-1)/bins.sum()
        else:
            error = error.mean(-1)
        loss = loss+spectral*(weight*error).mean()
    return loss


# v2 condition layout [domain one-hot, rate_known, irregularity_known, rate, irregularity, std]: rate_known is 5th last.
RATE_KNOWN = -5
RATE = -3
# Loop 7 wrist slowing: the only scaffolded wrist windows (11 of 83) beat at 101-120 bpm.
SLOW_KEEP_S = (.5, .1)                   # absolute time kept after each peak (upstroke, systole, reflected wave), before the next
SLOW_FROM_BPM, SLOW_STEP_BPM = 40., 5.


def slow_beats(row, phase, k, keep=SLOW_KEEP_S, fs=FS):
    """Slow one window's beats by k >= 1 the way a slower heart does: per beat, the first keep[0] s after the peak
    and the last keep[1] s before the next keep their absolute timing and only the diastolic run-off between them is
    stretched. Returns (signal, beat phase); peaks stay at integer phase."""
    length = len(row)
    cycles = np.arange(np.ceil(phase[0]), np.floor(phase[-1])+1)
    peaks = np.interp(cycles, phase, np.arange(length))
    ibi = np.diff(peaks)
    after, before = keep[0]*fs, keep[1]*fs
    new_ibi = k*ibi
    new_peaks = peaks[0]+np.r_[0, np.cumsum(new_ibi)]
    t = np.arange(length, dtype=float)
    beat = np.clip(np.searchsorted(new_peaks, t, side="right")-1, 0, len(ibi)-1)
    offset, old, new = t-new_peaks[beat], ibi[beat], new_ibi[beat]
    lo, hi = np.minimum(after, old-before), new-before
    middle = lo+(offset-lo)*(old-before-lo)/np.maximum(hi-lo, 1e-9)
    source = np.where(offset < lo, offset, np.where(offset > hi, old-(new-offset), middle))
    source = np.where(t < new_peaks[0], offset, source)
    signal = np.interp(np.clip(peaks[beat]+source, 0, length-1), np.arange(length), row)
    return signal.astype(np.float32), (cycles[0]+beat+offset/new).astype(np.float32)


def slow_wrist_bank(signal, phase, usable, rate, wrist, band):
    """Slowed copies of the scaffolded wrist windows at SLOW_FROM_BPM, +SLOW_STEP_BPM, ... below their own rate, after
    the data view again (band: finish's |H|^2). A copy is kept only if it passes the real-window scaffold test
    (window_peaks, >= MIN_PEAKS, peak rate within RATE_TOLERANCE of the target): some wrist windows carry a periodic
    component that is not the pulse and would read as a faster rhythm once the beats slow. Returns (signals (m, L),
    phases (m, L), target rates (m,), source rows (m,))."""
    out = ([], [], [], [])
    for i in np.flatnonzero(wrist & usable):
        for target in np.arange(SLOW_FROM_BPM, rate[i]-SLOW_STEP_BPM/2, SLOW_STEP_BPM):
            y, p = slow_beats(signal[i], phase[i], rate[i]/target)
            y = finish(torch.tensor(y)[None, None], band)[0, 0].numpy()
            times = window_peaks(y)
            if times is None or len(times) < MIN_PEAKS:
                continue
            if abs(60*FS/np.median(np.diff(times))-target) > max(RATE_TOLERANCE[0], RATE_TOLERANCE[1]*target):
                continue
            for part, value in zip(out, (y, p, target, i)):
                part.append(value)
    if not out[0]:
        return np.zeros((0, signal.shape[1]), np.float32), np.zeros((0, signal.shape[1]), np.float32), np.zeros(0), np.zeros(0, int)
    return np.stack(out[0]).astype(np.float32), np.stack(out[1]), np.asarray(out[2]), np.asarray(out[3])


def swap_slow(signal, phase, condition, eligible, share, bank_signal, bank_phase, bank_condition, generator=None):
    """Replace a share of the eligible batch rows (scaffolded wrist) by random slowed copies with their own conditions."""
    pick = eligible & (torch.rand(len(signal), device=signal.device, generator=generator) < share)
    if not len(bank_signal) or not bool(pick.any()):
        return signal, phase, condition
    j = torch.randint(len(bank_signal), (int(pick.sum()),), device=signal.device, generator=generator)
    signal, phase, condition = signal.clone(), phase.clone(), condition.clone()
    signal[pick], phase[pick], condition[pick] = bank_signal[j][:, None].to(signal.dtype), bank_phase[j], bank_condition[j]
    return signal, phase, condition


class FlowGenerator(nn.Module):
    """generator(z, condition) -> (n, 1, LENGTH) in [0, 1], like PhysioMix; z is the starting noise and
    (reversed) the rhythm noise. Fixed-step Heun integration from t=1 to 0; guidance > 1 mixes in the
    unconditioned velocity (classifier-free guidance). Deterministic given z.

    flag_scaffold: the scaffold is given only when the condition says the rate is known, as in training,
    where windows with masked rate labels (most wrist exercise, a third of AF) never had one. Otherwise
    every prompt gets a scaffold. export() gives TorchScript with the integration loop kept as a loop."""
    def __init__(self, size, center, scale, sample_steps=8, guidance=1., width=1., flag_scaffold=False, t_end=0.,
                 finish_filter=False):
        super().__init__()
        channels = tuple(int(round(c*width/8))*8 for c in (32, 64, 128, 160, 160))
        self.net = UNet1D(size, channels)
        self.sample_steps, self.guidance, self.flag_scaffold = int(sample_steps), float(guidance), bool(flag_scaffold)
        # t_end > 0 stops integrating with a little white noise left; finish_filter then applies the data view
        # (0.5-8 Hz) on a reflection-padded window, like sensor noise passing the same filter as the real data.
        self.t_end, self.finish_filter = float(t_end), bool(finish_filter)
        self.register_buffer("band", torch.tensor(view_mask("v3", LENGTH+2*FINISH_PAD)), persistent=False)
        self.register_buffer("center", torch.tensor(center, dtype=torch.float32))
        self.register_buffer("scale", torch.tensor(scale, dtype=torch.float32))
        self.register_buffer("time", torch.arange(LENGTH, dtype=torch.float32)/FS)

    def scaffold_of(self, z, condition):
        raw = condition[:, -3:]*self.scale+self.center
        hz = (raw[:, 0]/60).clamp(*HZ_RANGE)
        phase = constructed_phase(z, hz, raw[:, 1].clamp(0, IRR_MAX), self.time)
        present = condition[:, RATE_KNOWN] > .5 if self.flag_scaffold else torch.ones_like(hz, dtype=torch.bool)
        return scaffold(phase, present)

    def velocity(self, x, t, scaffold3, condition):
        tt = torch.zeros_like(x[:, 0, 0])+t
        if self.guidance == 1.:
            return self.net(x, tt, scaffold3, condition, torch.ones_like(tt))
        both = self.net(torch.cat((x, x)), torch.cat((tt, tt)), torch.cat((scaffold3, scaffold3)),
                        torch.cat((condition, condition)), torch.cat((torch.ones_like(tt), torch.zeros_like(tt))))
        cond, uncond = both.chunk(2)
        return uncond+self.guidance*(cond-uncond)

    def forward(self, z, condition):
        s = self.scaffold_of(z, condition)
        x = z[:, None]
        steps, span = self.sample_steps, 1-self.t_end
        for i in range(steps):
            t, t_next = 1-span*i/steps, 1-span*(i+1)/steps
            v = self.velocity(x, t, s, condition)
            proposal = x+(t_next-t)*v
            if i < steps-1 or self.t_end > 0:
                x = x+(t_next-t)*.5*(v+self.velocity(proposal, t_next, s, condition))
            else:
                x = proposal
        if self.finish_filter:
            x = finish(x, self.band)
        return (x-x.amin(-1, keepdim=True))/(x.amax(-1, keepdim=True)-x.amin(-1, keepdim=True)).clamp_min(1e-6)

    def export(self, z, condition):
        """TorchScript: the U-Net traced once (one network evaluation), the sampler scripted around it.
        Tracing forward() instead unrolls every step into one graph (tens of network copies)."""
        net = self.net.eval()
        n = len(z)
        example = (z[:, None], torch.full((n,), .5), self.scaffold_of(z, condition), condition, torch.ones(n))
        sampler = FlowSampler(torch.jit.trace(net, example), self.center, self.scale, self.time, self.band,
                              self.sample_steps, self.guidance, self.flag_scaffold, self.t_end, self.finish_filter)
        return torch.jit.script(sampler)


def finish(x, band, pad: int = FINISH_PAD):
    """Zero-phase data-view filter of (n, 1, L) windows over a reflection-padded copy, cropped back to L."""
    length = x.shape[-1]
    y = torch.cat((x[..., 1:pad+1].flip(-1), x, x[..., length-pad-1:length-1].flip(-1)), -1)
    y = torch.fft.irfft(torch.fft.rfft(y-y.mean(-1, keepdim=True), dim=-1)*band, n=length+2*pad, dim=-1)
    return y[..., pad:pad+length]


class FlowSampler(nn.Module):
    """Scriptable twin of FlowGenerator.forward around a traced velocity network."""
    def __init__(self, net, center, scale, time, band, sample_steps: int, guidance: float, flag_scaffold: bool,
                 t_end: float, finish_filter: bool):
        super().__init__()
        self.net = net
        self.register_buffer("center", center.clone())
        self.register_buffer("scale", scale.clone())
        self.register_buffer("time", time.clone())
        self.register_buffer("band", band.clone())
        self.sample_steps, self.guidance, self.flag_scaffold = sample_steps, guidance, flag_scaffold
        self.t_end, self.finish_filter, self.pad = t_end, finish_filter, FINISH_PAD
        self.hz_lo, self.hz_hi, self.irr_max, self.beats = HZ_RANGE[0], HZ_RANGE[1], IRR_MAX, BEATS
        self.rate_known = RATE_KNOWN

    def scaffold_of(self, z, condition):
        raw = condition[:, -3:]*self.scale+self.center
        hz = (raw[:, 0]/60).clamp(self.hz_lo, self.hz_hi)
        sigma = raw[:, 1].clamp(0., self.irr_max)
        u = z.flip(1)
        ibi = torch.exp(sigma[:, None]*u[:, :self.beats]-.5*sigma[:, None]**2)/hz[:, None]
        first = -ibi[:, :1]*torch.sigmoid(u[:, self.beats:self.beats+1])
        peaks = first+torch.cumsum(ibi, 1)-ibi
        index = ((peaks[:, :, None] <= self.time[None, None]).sum(1)-1).clamp(0, self.beats-1)
        phase = index.to(z.dtype)+(self.time[None]-peaks.gather(1, index))/ibi.gather(1, index)
        if self.flag_scaffold:
            flag = (condition[:, self.rate_known] > .5).to(z.dtype)[:, None]
        else:
            flag = torch.ones_like(hz)[:, None]
        angle = 2*math.pi*phase
        return torch.stack((angle.sin()*flag, angle.cos()*flag, flag.expand_as(phase)), 1)

    def velocity(self, x, t: float, s, condition):
        tt = torch.zeros_like(x[:, 0, 0])+t
        if self.guidance == 1.:
            return self.net(x, tt, s, condition, torch.ones_like(tt))
        both = self.net(torch.cat((x, x)), torch.cat((tt, tt)), torch.cat((s, s)), torch.cat((condition, condition)),
                        torch.cat((torch.ones_like(tt), torch.zeros_like(tt))))
        parts = both.chunk(2)
        return parts[1]+self.guidance*(parts[0]-parts[1])

    def forward(self, z, condition):
        s = self.scaffold_of(z, condition)
        x = z[:, None]
        steps, span = self.sample_steps, 1.-self.t_end
        for i in range(steps):
            t, t_next = 1.-span*i/steps, 1.-span*(i+1)/steps
            v = self.velocity(x, t, s, condition)
            proposal = x+(t_next-t)*v
            if i < steps-1 or self.t_end > 0.:
                x = x+(t_next-t)*.5*(v+self.velocity(proposal, t_next, s, condition))
            else:
                x = proposal
        if self.finish_filter:
            x = finish(x, self.band, self.pad)
        return (x-x.amin(-1, keepdim=True))/(x.amax(-1, keepdim=True)-x.amin(-1, keepdim=True)).clamp_min(1e-6)
